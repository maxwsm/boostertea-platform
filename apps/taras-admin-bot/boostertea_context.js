/**
 * Елементарний RAG процесор: шукає ключові слова і збирає оптимізований промпт
 */
function getRagContext(userText) {
  const text = userText.toLowerCase();
  let systemPrompt = CONTEXT_MODULES.BASE_PERSONA;

  // Keyword Matching Logic (Light RAG)
  if (text.match(/втомився|не можу|сдуг|фокус|увага|тайм|часу|боюсь|лінь|мотивація/i)) {
    systemPrompt += '\\n' + CONTEXT_MODULES.PHILOSOPHY;
  }
  
  if (text.match(/баг|помилка|база|twa|ношен|прісма|код/i)) {
    systemPrompt += '\\n' + CONTEXT_MODULES.TECH_ARCH;
  }

  if (text.match(/блогер|ютуб|реклама|продаж|b2b|літери|літри|коробки|отправить/i)) {
    systemPrompt += '\\n' + CONTEXT_MODULES.MARKETING_STRATEGY;
  }

  if (text.match(/договір|штраф|партнер|відсоток|амбасадор|умови|угода|whitepaper|вайтпепер|правила|інвест/i)) {
    systemPrompt += '\\n' + CONTEXT_MODULES.WHITEPAPER;
  }

  return systemPrompt;
}

module.exports = { getRagContext };
