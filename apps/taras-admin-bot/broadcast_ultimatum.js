require('dotenv').config();
const { Telegraf } = require('telegraf');
const { PrismaClient } = require('./prisma/client');

const bot = new Telegraf(process.env.BOT_TOKEN);
const prisma = new PrismaClient();

const ULTIMATUM_TEXT = `🚨 [SYSTEM OVERRIDE: ЧАСТИНА 2 — УМОВИ ТА ПРАВИЛА ГРИ] 🚨

Доповнення до попереднього повідомлення. Ігри остаточно скінчилися, тому карти на стіл. Потрібно, щоб кожен чітко розумів, що саме йому дається в руки, що він матиме з цього, і чому умови саме такі.

Що ви отримуєте? Ви отримуєте не стартап для розваги, а готову до національного масштабу екосистему. Ваш прибуток і ваша частка компанії будуть реальними. Але вони не даються просто так в подарунок.

ОСНОВНІ ПОЛОЖЕННЯ ДОГОВОРУ (на що звернути увагу з юристом):
1. Юридична сила: Договір буде нотаріально завіреним та матиме фіксований строк дії (терміновий). Жодних "дружніх" домовленостей на словах.
2. Правило 80/100 (Ключовий тригер): Підписант вступає в компанію як повноцінний партнер (на всі 100% частки/прав) ТІЛЬКИ в разі виконання мінімум 80% закладеного навчання (Академії) та поставлених завдань. БЕЗУМОВНО. 

Чому тільки так і по-іншому не буде?
Тому що цей бізнес вимагає капітальної дисципліни. Ви повинні розуміти цінність активу, до якого вас підпускають. Партнерство — це не лише поділ прибутку, це поділ відповідальності.

Перетравіть цю інформацію і підготуйтесь до зустрічі з юристом.`;

async function broadcastUltimatum() {
  try {
    const users = await prisma.user.findMany({
      where: {
        role: { not: 'maks' } // Відправляємо всім, крім фаундера
      }
    });

    if (users.length === 0) {
      console.log("Команду не знайдено в базі!");
      return;
    }

    console.log(`Знайдено ${users.length} людей для відправки Ультиматуму.`);

    for (const u of users) {
      try {
        await bot.telegram.sendMessage(u.telegramId, ULTIMATUM_TEXT);
        console.log(`✅ Відправлено: ${u.role} (${u.name || u.telegramId})`);
      } catch (err) {
        console.error(`❌ Помилка відправки для ${u.role} (${u.telegramId}):`, err.message);
      }
    }
    
    console.log("🔥 Ультиматум успішно запущено.");
  } catch (error) {
    console.error("Помилка БД:", error);
  } finally {
    await prisma.$disconnect();
  }
}

broadcastUltimatum();
